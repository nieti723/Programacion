package boletin.ejercicio02;

public class TipoArgumento {
	public static void tipoArgumento(int n) {
		System.out.println("Soy un número entero");
	}
	
	public static void tipoArgumento(byte b) {
		System.out.println("Soy un byte");
	}
	
	public static void tipoArgumento(short s) {
		System.out.println("Soy un número entero corto");
	}
	
	public static void tipoArgumento(long n) {
		System.out.println("Soy un número entero largo");
	}
	
	public static void tipoArgumento(String s) {
		System.out.println("Soy una cadena");
	}
	
	public static void tipoArgumento(char c) {
		System.out.println("Soy un caracter");
	}
	
	public static void tipoArgumento(double d) {
		System.out.println("Soy un número decimal largo");
	}
	
	public static void tipoArgumento(float f) {
		System.out.println("Soy un número decimal");
	}
	
	public static void tipoArgumento(boolean b) {
		System.out.println("Soy un booleano");
	}
}
